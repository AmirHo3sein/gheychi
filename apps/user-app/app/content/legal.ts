/**
 * Legal copy for the three public policy pages (/terms, /privacy, /booking-policy).
 *
 * Typed data rather than markup so the text has ONE source for the pages, the sitemap and the
 * tests, and so a reviewer (a lawyer) can read and edit prose without touching components.
 *
 * Dynamic values are `{{tokens}}` resolved by the renderer:
 *  - `{{depositPercent}}`, `{{depositMinToman}}`, `{{cancellationWindowHours}}` -- live platform
 *    config (GET /platform-config/booking-terms), so the page can never state a number the
 *    product doesn't actually enforce.
 *  - `{{operatorName|Email|Phone|Address|Registration}}` -- the legal operator's identity from
 *    runtime config. A block that references an UNSET operator token is omitted entirely: the
 *    page never shows a placeholder and never invents a company name or contact.
 *  - `when: 'paymentsOn' | 'paymentsOff'` -- blocks that only apply while online payment is
 *    enabled / disabled (feature_online_payment_enabled). Gheychi currently runs free-booking
 *    only, so the live page must not describe deposits as if they were being collected.
 *
 * This text describes what the product actually does today (verified against the code on
 * 2026-10-08). It is NOT legal advice: have it reviewed by a lawyer and fill in the operator
 * identity before launch. Keep it in sync with the product -- if a rule changes in the API,
 * change the sentence here in the same commit.
 */

export type LegalCondition = 'paymentsOn' | 'paymentsOff'

export type LegalBlock =
  | { type: 'p'; text: string; when?: LegalCondition }
  | { type: 'ul'; items: string[]; when?: LegalCondition }
  | { type: 'note'; text: string; when?: LegalCondition }

export interface LegalSection {
  id: string
  title: string
  blocks: LegalBlock[]
}

export interface LegalDocument {
  slug: 'terms' | 'privacy' | 'booking-policy'
  title: string
  description: string
  /** ISO date (YYYY-MM-DD) of the last substantive change. */
  updatedAt: string
  intro: string
  sections: LegalSection[]
}

